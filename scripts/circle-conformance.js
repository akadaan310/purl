// npm run circle:conformance — run every constitutional check against a freshly started
// circle (substrate + ACSP spawned from sibling repositories) and write the result.
//   writes circle/conformance/latest.json and circle/CONSTITUTION-CONFORMANCE.md (generated)
import { writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { startCircle } from './circle-lib.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SUBSTRATE_DIR = process.env.SUBSTRATE_DIR ?? resolve(ROOT, '..', 'substrateIO');
const ACSP_DIR = process.env.ACSP_DIR ?? resolve(ROOT, '..', 'NetGovComEduGovOrgEduGovComNet');

export async function ownerResource(acspBase, title) {
  const intent = await (await fetch(`${acspBase}/new?format=json&session_id=owner-human&title=${encodeURIComponent(title)}`)).json();
  const created = await (await fetch(`${acspBase}/r`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(intent.request) })).json();
  return created.resource_id; // the owner capability in `created` is deliberately dropped: the circle never holds it
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const c = await startCircle({ substrateDir: SUBSTRATE_DIR, acspDir: ACSP_DIR, substratePort: 38765, acspPort: 38787 });
  try {
    c.cfg.acspTestResource = await ownerResource(c.acspBase, 'circle conformance');
    const r = await fetch(`${c.base}/conformance/runs?session=conformance-runner`, { method: 'POST' });
    const doc = await r.json();
    if (r.status !== 201) throw new Error(JSON.stringify(doc));
    const { constitution: _c, moves: _m, protocol: _p, kind: _k, ...run } = doc;
    mkdirSync(join(ROOT, 'circle', 'conformance'), { recursive: true });
    writeFileSync(join(ROOT, 'circle', 'conformance', 'latest.json'), JSON.stringify({ ...run, commits: c.cfg.commits }, null, 1) + '\n');
    const consti = c.circle.constitution();
    const rows = consti.doc.clauses.map((k) => {
      const s = run.clauses.find((x) => x.id === k.id);
      const checks = s.checks.map((x) => `${x.ok === true ? '✓' : x.ok === false ? '✗' : '·'} \`${x.name}\` — ${String(x.detail ?? '').replace(/\|/g, '/')}`).join('<br>') || '—';
      return `| ${k.id} | ${k.text} | ${k.governs.join(', ')} | ${k.enforcement.kind}: ${k.enforcement.mechanism} | ${checks} | **${s.status}** | ${k.interpretation ?? ''} |`;
    });
    const md = `# Constitutional conformance (generated)

Generated by \`npm run circle:conformance\` from a live run. Do not edit by hand.
Run ${run.run} at ${run.ran_at}, purl commit \`${run.commit}\`, substrateIO \`${c.cfg.commits.substrateIO}\`, ACSP \`${c.cfg.commits.acsp}\`.
Constitution v${consti.doc.version}, content id \`${consti.content_id}\` ([constitution-v1.json](constitution/constitution-v1.json)).
Address of every clause: \`GET /constitution/clauses/{id}\`. Latest run: \`GET /conformance\`.

Summary (categorical, no score): ${Object.entries(run.summary).map(([k, v]) => `${k} ${v}`).join(' · ')}.

Status meanings: TESTED = all of the clause's checks passed against a live circle in this run.
FAILED = at least one failed. IMPLEMENTED = mechanism exists but a check could not run.
EXTERNAL = enforced and tested by another system (cited). HUMAN_REVIEWED = no mechanical
check. CONFLICTING = its sources disagree and no amendment has resolved it. A TESTED clause
is tested *as this run exercised it*, not proved.

| Clause | Text | Governs | Enforcement | Checks (this run) | Status | Unresolved interpretation |
|---|---|---|---|---|---|---|
${rows.join('\n')}

Additional checks attached through [enforcement.json](constitution/enforcement.json) (content id \`${run.enforcement}\`):
verification only, never a change to what a clause says.

## Amendment history

* None adopted. The constitution is v1, unchanged since it was written.
* **A-001 (proposed, awaiting a human decision):** move every clause→check mapping out of
  \`constitution-v1.json\` into \`enforcement.json\`. Evidence: adding checks after EXP-CIRCLE-FRESH
  (F-C1, F-C2) would otherwise have changed the constitution's content id, which would be a
  constitutional change made for an engineering reason. Consequence if adopted: the constitution
  holds only clauses, sources and amendment rules. Verification can then grow without amendments.
* **K-18 conflict (open):** MUSA art. I ("nothing waits for approval … to publish") against
  K-04/ACSP owner resolution. Needs the operator's decision; the circle publishes only as proposals.
* Amendment proposals created by conformance probes are stored as PURL resources of type
  \`amendment\` (status \`proposed\`) and change nothing.
`;
    writeFileSync(join(ROOT, 'circle', 'CONSTITUTION-CONFORMANCE.md'), md);
    console.log(JSON.stringify(run.summary));
    for (const k of run.clauses.filter((x) => x.status === 'FAILED')) console.log('FAILED', k.id, JSON.stringify(k.checks));
  } finally {
    await c.close();
  }
}
